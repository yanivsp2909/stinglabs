"""The live differential replay, as a gate.

This repo has no Makefile, so `pytest` IS the gate. What runs here is the
mechanism — the classification, the state witness, the baseline contract — plus
the full replay if and only if a vendored fixture exists.

THE FIXTURE IS NOW VENDORED, so these tests really do gate. `logs/live-fixture/`
holds redacted whole sessions, regenerated by `tools/redact_logs.py` — never by
hand, because a fixture nobody can rebuild is a fixture nobody can trust.

Redaction is verdict-preserving, measured rather than assumed: one snapshot
replayed twice, original vs redacted, gave an identical difference set and zero
disagreeing verdicts. Every path rule tests a RELATIONSHIP, never the specific
username, so a consistent global rename including cwd leaves them all intact.

The tool itself is free either way: `python3 runner/replay_live.py`.
"""
import json
from pathlib import Path

import pytest

from tools.redact_logs import IDENTITY_PLACEHOLDER
from runner.replay_live import (ASSUMED_CWD, BASELINE, NO_CONTENT, REPLAYABLE,
                                STATE_DIVERGED, TRUNCATED, classify, replay,
                                state_implied_by)
from private_fixtures import needs_live_fixture  # noqa: E402

ROOT = Path(__file__).parent.parent
FIXTURE = ROOT / "logs" / "live-fixture"

# THE FIXTURE'S PATHS ARE RENAMED, so it must be replayed against the RENAMED cwd.
# Replaying it against the real one would put every action outside the project and
# manufacture `write_outside` denials that never happened — the fixture would then
# assert something the engine never decided, which is the exact failure the
# redaction question was worried about.
# ⚠ FIXTURE DATA, NOT A LIVE DERIVATION — AND IT USED TO BE THE SECOND.
# It read `redacted_cwd("/Users/<the author>/sting/sting-engine")`: the author's
# own path put through the RUNNING MACHINE's substitution list. On his laptop
# that yields `/Users/dev/…` and matches the fixture; on any other machine
# nothing matches, the name survives, and this gate — the standing replay —
# replays the cwd-less records against a root that appears nowhere in the
# fixture. A gate whose input depends on who runs it is not a gate.
FIXTURE_CWD = f"/Users/{IDENTITY_PLACEHOLDER}/sting/sting-engine"


# ================================================= the state witness
# The trick that makes a difference attributable: a rule id names a gated branch,
# so it PROVES what the session state was when the action was recorded.
@pytest.mark.parametrize("rule_id,untrusted,secret", [
    ("untrusted_unexpected:git_push", True, False),
    ("untrusted_local:git_commit", True, False),
    ("untrusted_destructive", True, False),
    ("secret_exact:git_push", False, True),
    ("secret_derived:network_egress", False, True),
    ("secret_session_unverified:git_commit", False, True),
    (None, False, False),
    ("irreversible_action", False, False),
    ("degraded_no_state", False, False),
])
def test_a_rule_id_witnesses_the_state_it_required(rule_id, untrusted, secret):
    assert state_implied_by(rule_id) == (untrusted, secret)


@pytest.mark.parametrize("rule_id", [
    "untrusted_unexpected:mcp_tool_call",
    "untrusted_expected:unknown_tool_call",
    "untrusted_local:security_critical",
])
def test_a_holds_secret_gated_SINK_witnesses_secret_too(rule_id):
    """THE REFINEMENT THAT MIS-ATTRIBUTED 13 DIFFERENCES. These sinks are gated on
    holds_secret inside check_sinks, so their presence proves the session held
    secrets regardless of what the ladder branch was called. Without this, an MCP
    call recorded as `untrusted_unexpected:mcp_tool_call` looked like a policy
    change when the replay simply never reconstructed the secret."""
    untrusted, secret = state_implied_by(rule_id)
    assert secret is True, rule_id


# ================================================= classification
def test_a_write_is_never_compared_because_content_is_not_recorded():
    """INHERENT, not a defect. `carries_secret()` and `weakens_security()` read
    content, content can be large and can BE the secret, so logging it is not the
    fix. It must be counted, never silently passed."""
    for kind in ("WRITE", "EDIT"):
        klass, _cmd = classify({"kind": kind, "command": None}, Path("/x"))
        assert klass == NO_CONTENT


def test_a_clipped_command_with_no_sidecar_is_not_compared():
    klass, _cmd = classify(
        {"kind": "EXEC", "command": "x" * 40, "command_clipped": True,
         "command_sha256": "0" * 64}, Path("/nonexistent"))
    assert klass == TRUNCATED


def test_a_record_predating_the_cwd_field_is_flagged_not_dropped():
    """213 of 271 historical records have no cwd. Dropping them would answer
    nothing, and 92.8% of live commands begin `cd <root> &&` so a supplied cwd is
    almost certainly right — the caveat travels with the number instead."""
    klass, _cmd = classify({"kind": "EXEC", "command": "git status"}, Path("/x"))
    assert klass == ASSUMED_CWD


def test_a_record_with_cwd_is_fully_replayable():
    klass, _cmd = classify(
        {"kind": "EXEC", "command": "git status", "cwd": "/repo"}, Path("/x"))
    assert klass == REPLAYABLE


# ================================================= the baseline contract
def test_every_baseline_entry_carries_a_reason():
    """An entry without a reason is a regression nobody looked at. This is the
    only thing separating an intended change from a regression, so it is the one
    property that must not rot."""
    if not BASELINE.exists():
        pytest.skip("no baseline yet")
    accepted = json.loads(BASELINE.read_text()).get("accepted", {})
    missing = [k for k, v in accepted.items()
               if not v.get("reason") or v["reason"].startswith(("TODO", "UNEXPLAINED"))]
    assert not missing, f"baseline entries with no reason: {missing}"


def test_every_baseline_reason_names_a_commit_or_says_why_not():
    """A reason that does not name what changed is a note, not an explanation."""
    if not BASELINE.exists():
        pytest.skip("no baseline yet")
    accepted = json.loads(BASELINE.read_text()).get("accepted", {})
    vague = [k for k, v in accepted.items()
             if not any(t in v["reason"] for t in
                        ("—", "-", "REPLAY", "CORRECT", "inversion"))]
    assert not vague, vague


# ================================================= the replay itself
@needs_live_fixture
def test_the_vendored_fixture_exists_so_this_actually_gates():
    """A gate that skips itself is a habit, not a gate.

    `logs/live-fixture/` is committed, so the two tests below MUST run. This test
    is what turns "skipped when absent" into "fails if someone removes it" — the
    difference the owner asked for explicitly."""
    assert FIXTURE.is_dir(), (
        f"{FIXTURE} is missing. Regenerate with "
        f"`python3 tools/redact_logs.py --out logs/live-fixture`.")
    assert list(FIXTURE.glob("*.jsonl")), "fixture directory is empty"


def test_no_unexplained_differences_against_the_vendored_logs():
    result = replay([FIXTURE], FIXTURE_CWD)
    accepted = (json.loads(BASELINE.read_text()).get("accepted", {})
                 if BASELINE.exists() else {})
    unexplained = [d["key"] for d in result["diffs"] if d["key"] not in accepted]
    assert not unexplained, (
        f"{len(unexplained)} verdict changes on real recorded actions with no "
        f"reason in {BASELINE.name}: {unexplained[:10]}")


def test_the_replay_is_deterministic():
    """The default world answers nothing, so two runs on the same logs must agree.
    A gate that depends on the machine's current git index is not a gate."""
    first = replay([FIXTURE], FIXTURE_CWD)
    second = replay([FIXTURE], FIXTURE_CWD)
    assert [d["key"] for d in first["diffs"]] == [d["key"] for d in second["diffs"]]
    assert first["compared"] == second["compared"]


# ================================================= cross-root de-duplication
def test_a_session_present_in_two_roots_is_not_replayed_twice(tmp_path):
    """FOUND WHILE MEASURING ENFORCE READINESS, and it corrupted the answer.

    A session can appear in more than one root — a live log under
    `~/.sting/dogfood` and an archived copy of the SAME session. Merging them
    naively replays the overlapping actions twice, and that does not merely
    inflate counts: `mark_sources` and `propagate` run again, so the session
    carries taint from actions that happened once and every later verdict is
    judged against a session that never existed.

    Measured when found: 1f089cfa had 22 records in one root and 485 in the
    other with 22 seqs overlapping, and the duplicate replay reported 82 denials
    where the deduped one reports the same 82 but from 808 actions rather than
    823 — and one baseline difference turned out to be pure artifact.
    """
    import json as _json
    live, archive = tmp_path / "live", tmp_path / "archive"
    live.mkdir(), archive.mkdir()
    shared = [{"event": "decision", "session_id": "s1", "seq": i, "kind": "EXEC",
               "decision": "ALLOW", "rule_id": None, "cwd": "/repo",
               "command": f"echo {i}"} for i in (1, 2, 3)]
    (live / "s1.log.jsonl").write_text(
        "\n".join(_json.dumps(r) for r in shared) + "\n")
    (archive / "s1.log.jsonl").write_text(
        "\n".join(_json.dumps(r) for r in shared) + "\n")

    both = replay([live, archive], str(ROOT))
    one = replay([live], str(ROOT))
    assert both["records"] == one["records"] == 3, (
        f"the same session counted twice: {both['records']} vs {one['records']}")


def test_the_longer_record_wins_when_two_roots_disagree(tmp_path):
    """An archived copy is usually complete and the live file a truncated tail,
    so the longer command is the better evidence."""
    import json as _json
    a, b = tmp_path / "a", tmp_path / "b"
    a.mkdir(), b.mkdir()
    short = {"event": "decision", "session_id": "s1", "seq": 1, "kind": "EXEC",
             "decision": "ALLOW", "cwd": "/repo", "command": "git st"}
    long = {**short, "command": "git status --porcelain --branch"}
    (a / "s1.log.jsonl").write_text(_json.dumps(short) + "\n")
    (b / "s1.log.jsonl").write_text(_json.dumps(long) + "\n")
    result = replay([a, b], str(ROOT))
    assert result["records"] == 1
